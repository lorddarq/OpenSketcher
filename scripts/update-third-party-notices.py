#!/usr/bin/env python3
"""Rebuild/check locked-crate notices using Cargo's cache and pinned upstream snapshots."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def font_notices(path):
    """Read copyright, trademark, author, and license records from a bundled sfnt font."""
    data = path.read_bytes()
    tables = struct.unpack_from('>H', data, 4)[0]
    offset = next(offset for tag, _, offset, _ in
                  (struct.unpack_from('>4sIII', data, 12 + 16*i) for i in range(tables))
                  if tag == b'name')
    _, count, strings = struct.unpack_from('>HHH', data, offset)
    notices = set()
    for i in range(count):
        platform, _, _, kind, length, start = struct.unpack_from('>6H', data, offset + 6 + 12*i)
        if kind in (0, 7, 8, 9, 13, 14):
            text = data[offset+strings+start:offset+strings+start+length].decode(
                'utf-16-be' if platform in (0, 3) else 'mac-roman').strip()
            if text:
                notices.add(text)
    return '\n\n'.join(sorted(notices))


def generate():
    metadata = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--offline', '--format-version', '1'], cwd=ROOT))
    packages = sorted((p for p in metadata['packages'] if p['source']),
                      key=lambda p: (p['name'], p['version']))
    supplements = json.loads((ROOT/'third-party/upstream-notices.json').read_text())
    upstream = {package: entry for entry in supplements.values() for package in entry['packages']}
    texts = {}

    def notice(text):
        text = text.strip()
        key = hashlib.sha256(text.encode()).hexdigest()[:16]
        texts[key] = text
        return key

    apache = notice((ROOT/'LICENSE').read_text())
    cc0 = notice((ROOT/'third-party/CC0-1.0.txt').read_text())
    # Two old MIT crates publish only a Cargo license declaration, with no notice file.
    # Retain the declared authors below; do not invent copyright dates or statements.
    mit_package = next(p for p in packages if p['name'] == 'serde')
    mit_text = (Path(mit_package['manifest_path']).parent/'LICENSE-MIT').read_text()
    mit = notice('MIT License\n\n' + mit_text[mit_text.index('Permission is hereby granted'):])
    rows = []
    for package in packages:
        name = package['name'] + ' ' + package['version']
        directory = Path(package['manifest_path']).parent
        files = sorted(f for f in directory.rglob('*') if f.is_file()
                       and any(word in f.name.lower() for word in
                               ('license', 'licence', 'notice', 'copyright', 'copying', 'authors'))
                       and f.suffix.lower() not in ('.rs', '.ttf', '.png', '.json'))
        sources = []
        for file in files:
            sources.append((str(file.relative_to(directory)), notice(file.read_text())))
        if name in upstream:
            for file in upstream[name]['files']:
                sources.append((file['url'], notice(file['text'])))
        if not sources and name not in upstream and package['name'] not in ('convert_case', 'dispatch', 'hexf-parse'):
            raise ValueError(f'Missing upstream notices for {name}; inspect its pinned source')
        if 'Apache-2.0' in (package['license'] or ''):
            sources.append(('Apache-2.0 license text', apache))
        if not sources:
            if package['name'] in ('convert_case', 'dispatch'):
                sources.append(('MIT declaration in published Cargo.toml; standard MIT terms', mit))
            elif package['license'] == 'CC0-1.0':
                sources.append(('CC0 declaration; SPDX license-list-data v3.27.0 text', cc0))
            else:
                raise ValueError(f'Missing notices for {name}; inspect the pinned upstream source')
        if package['name'] == 'epaint_default_fonts':
            for font in sorted((directory/'fonts').glob('*.ttf')):
                text = font_notices(font)
                if text:
                    sources.append((f'fonts/{font.name} embedded name-table notices', notice(text)))
        credits = '; '.join(package['authors']) or 'See preserved upstream notices.'
        links = '; '.join(f'{source}: [text](#notice-{key})' for source, key in sources)
        rows.append(f"| {name} | {package['license']} | {credits} | {package['repository'] or package['source']} | {links} |")
    lock = hashlib.sha256((ROOT/'Cargo.lock').read_bytes()).hexdigest()
    lines = ['# Third-party notices', '',
             'Generated by `python3 scripts/update-third-party-notices.py`. Do not edit generated text.', '',
             f'Cargo.lock SHA-256: `{lock}`. Inventory: {len(packages)} locked registry packages.', '',
             'This conservative inventory includes target-specific, optional, and build dependencies; not every listed package is linked into every desktop artifact. Crate authors below are manifest credits, not inferred copyright holders. Upstream notices and font metadata are preserved verbatim in the text sections. License alternatives remain alternatives; this inventory does not relicense dependencies.', '',
             'Published crate files are the primary source. Missing archive notices are supplemented from exact upstream revisions recorded in `third-party/upstream-notices.json`. convert_case 0.4.0 and dispatch 0.2.0 declare MIT without a license file at their published revision; standard MIT terms and declared author credits are included. hexf-parse declares CC0; its text is from SPDX license-list-data v3.27.0. r-efi includes its grants and copyright notices in AUTHORS.', '',
             '| Package | Declared license | Declared authors | Upstream | Preserved notice sources |',
             '| --- | --- | --- | --- | --- |', *rows, '']
    for key, text in sorted(texts.items()):
        lines += [f'<a id="notice-{key}"></a>', '', f'## Notice {key}', '',
                  '\n'.join('    ' + line.rstrip() if line.strip() else '' for line in text.splitlines()), '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if committed notices differ')
    args = parser.parse_args()
    generated = generate()
    destination = ROOT/'THIRD_PARTY_NOTICES.md'
    if args.check:
        if not destination.exists() or destination.read_text() != generated:
            raise SystemExit('Third-party notices are stale. Run scripts/update-third-party-notices.py.')
        print('Third-party notices match the locked dependencies and preserved sources.')
    else:
        destination.write_text(generated)
        print(f'Wrote {destination.name}')
